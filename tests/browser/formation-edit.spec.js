import {test,expect} from '@playwright/test';
import {initialState} from '../../src/game.js';
test('formation swaps slots and replaces in either selection order without details',async({page})=>{
 const s=initialState();s.auto=false;
 await page.addInitScript(s=>{if(!localStorage.getItem('pokemon-days-v1'))localStorage.setItem('pokemon-days-v1',JSON.stringify(s));},s);
 await page.goto('/');
 const open=async()=>{await page.locator('.nav-button[data-action="collection"]').click();await page.locator('[data-action="formation"]').click();};
 await open();
 const card=id=>page.locator(`.collection-grid [data-id="${id}"]`);
 const slot=n=>page.locator(`[data-action="slot"][data-slot="${n}"]`);
 const party=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('pokemon-days-v1')).party);
 await expect(page.locator('.party-slot.occupied')).toHaveCount(5);
 await slot(0).click();await expect(card('starter-0')).toHaveClass(/formation-selected/);
 expect(await party()).toEqual(s.party);
 await slot(1).click();expect((await party()).slice(0,2)).toEqual(['starter-1','starter-0']);
 await slot(0).click();await card('starter-5').click();expect((await party())[0]).toBe('starter-5');
 await card('starter-1').click();await slot(1).click();expect((await party())[1]).toBe('starter-1');
 await card('starter-5').click();await card('starter-1').click();expect((await party()).slice(0,2)).toEqual(['starter-1','starter-5']);
 await card('starter-0').click();await card('starter-0').click();await expect(page.locator('.formation-selected')).toHaveCount(0);
 await expect(page.locator('.modal')).toHaveCount(0);
 const saved=await party();await page.reload();expect(await party()).toEqual(saved);
 await open();await slot(0).click();await page.locator('.selection-notice [data-action="removeSlot"]').click();await expect(page.locator('.party-slot.occupied')).toHaveCount(4);
 await card('starter-1').click();await slot(4).click();await expect(page.locator('.party-slot.occupied')).toHaveCount(5);
 await page.locator('[data-action="formation"]').click();await card('starter-0').click();await expect(page.locator('.detail-modal')).toBeVisible();
});
